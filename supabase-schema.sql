create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'عضو گروه',
  role text not null default 'member' check (role in ('member','admin')),
  approved boolean not null default false,
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'display_name', 'عضو گروه'));
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'admin' and approved = true
  );
$$;

create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 1000),
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.comments enable row level security;

drop policy if exists "read own profile or admin reads all" on public.profiles;
drop policy if exists "approved members read approved profiles" on public.profiles;
create policy "read own profile or admin reads all"
on public.profiles for select to authenticated
using (id = (select auth.uid()) or public.is_admin());

create policy "approved members read approved profiles"
on public.profiles for select to authenticated
using (
  approved = true
  and exists(select 1 from public.profiles me where me.id = (select auth.uid()) and me.approved = true)
);

drop policy if exists "admins update profiles" on public.profiles;
create policy "admins update profiles"
on public.profiles for update to authenticated
using (public.is_admin())
with check (public.is_admin());

drop policy if exists "approved members read comments" on public.comments;
create policy "approved members read comments"
on public.comments for select to authenticated
using (exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.approved=true));

drop policy if exists "approved members post comments" on public.comments;
create policy "approved members post comments"
on public.comments for insert to authenticated
with check (
  user_id = (select auth.uid())
  and exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.approved=true)
);

drop policy if exists "authors or admins delete comments" on public.comments;
create policy "authors or admins delete comments"
on public.comments for delete to authenticated
using (user_id = (select auth.uid()) or public.is_admin());

